CREATE FUNCTION public.create_reservation(p_shop_id uuid,p_customer_id bigint,p_product_id uuid,p_quantity integer,p_advance numeric,p_note text)
 RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$ DECLARE p public.produits; r bigint; BEGIN
 PERFORM public.require_shop(p_shop_id);
 SELECT * INTO p FROM public.produits WHERE id=p_product_id AND shop_id=p_shop_id AND actif FOR UPDATE;
 IF NOT FOUND OR p_quantity IS NULL OR p_quantity<=0 OR p.stock_quantite-p.reserved_quantity<p_quantity
 OR p_advance IS NULL OR p_advance<0 OR p_advance>p.prix*p_quantity THEN RAISE EXCEPTION 'Réservation ou stock disponible invalide'; END IF;
 INSERT INTO public.reservations(shop_id,customer_id,product_id,quantity,unit_price,paid_amount,status,note,created_by)
 VALUES(p_shop_id,p_customer_id,p_product_id,p_quantity,p.prix,p_advance,
 CASE WHEN p_advance=p.prix*p_quantity THEN 'paye' ELSE 'en_cours' END,p_note,auth.uid()) RETURNING id INTO r;
 UPDATE public.produits SET reserved_quantity=reserved_quantity+p_quantity WHERE id=p.id;
 IF p_advance>0 THEN INSERT INTO public.payments(shop_id,reservation_id,amount,note,created_by)
 VALUES(p_shop_id,r,p_advance,'Avance',auth.uid()); END IF;
 RETURN r; END $$;
CREATE FUNCTION public.add_payment(p_shop_id uuid,p_reservation_id bigint,p_amount numeric,p_note text) RETURNS void
 LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$ DECLARE r public.reservations; BEGIN
 PERFORM public.require_shop(p_shop_id);
 SELECT * INTO r FROM public.reservations WHERE id=p_reservation_id AND shop_id=p_shop_id FOR UPDATE;
 IF NOT FOUND OR r.status<>'en_cours' OR p_amount IS NULL OR p_amount<=0 OR p_amount>r.remaining_amount THEN RAISE EXCEPTION 'Paiement invalide'; END IF;
 UPDATE public.reservations SET paid_amount=paid_amount+p_amount,
 status=CASE WHEN paid_amount+p_amount=total_amount THEN 'paye' ELSE 'en_cours' END WHERE id=r.id;
 INSERT INTO public.payments(shop_id,reservation_id,amount,note,created_by) VALUES(p_shop_id,r.id,p_amount,p_note,auth.uid());
 END $$;
CREATE FUNCTION public.mark_reservation_remis(p_shop_id uuid,p_reservation_id bigint) RETURNS void
 LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$ DECLARE r public.reservations; v uuid; BEGIN
 PERFORM public.require_shop(p_shop_id);
 SELECT * INTO r FROM public.reservations WHERE id=p_reservation_id AND shop_id=p_shop_id FOR UPDATE;
 IF NOT FOUND OR r.status<>'paye' THEN RAISE EXCEPTION 'Réservation non payée ou déjà remise'; END IF;
 UPDATE public.produits SET reserved_quantity=reserved_quantity-r.quantity WHERE id=r.product_id AND shop_id=p_shop_id;
 v:=public.create_sale(p_shop_id,r.product_id,r.customer_id,r.quantity,r.unit_price);
 UPDATE public.reservations SET status='remis',sale_id=v WHERE id=r.id;
 END $$;
CREATE FUNCTION public.cancel_reservation(p_shop_id uuid,p_reservation_id bigint) RETURNS void
 LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$ DECLARE r public.reservations; BEGIN
 PERFORM public.require_shop(p_shop_id);
 SELECT * INTO r FROM public.reservations WHERE id=p_reservation_id AND shop_id=p_shop_id FOR UPDATE;
 IF NOT FOUND OR r.status NOT IN ('en_cours','paye') THEN RAISE EXCEPTION 'Annulation impossible'; END IF;
 -- Un remboursement doit être explicite : ne jamais inventer une sortie de caisse.
 IF r.paid_amount>0 THEN RAISE EXCEPTION 'Réservation avec paiement : remboursement à traiter avant annulation'; END IF;
 UPDATE public.produits SET reserved_quantity=reserved_quantity-r.quantity WHERE id=r.product_id;
 UPDATE public.reservations SET status='annule' WHERE id=r.id;
 END $$;
