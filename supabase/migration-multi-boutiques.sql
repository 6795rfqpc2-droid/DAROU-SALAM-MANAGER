CREATE OR REPLACE FUNCTION public.is_admin() RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=''
 AS $$ SELECT EXISTS(SELECT 1 FROM public.profiles WHERE id=auth.uid() AND role='admin' AND active IS TRUE) $$;
CREATE FUNCTION public.can_access_shop(p_shop_id uuid) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=''
 AS $$ SELECT EXISTS(SELECT 1 FROM public.profiles p JOIN public.shops s ON s.id=p_shop_id AND s.active
 WHERE p.id=auth.uid() AND p.active IS TRUE AND (p.role='admin' OR EXISTS(
 SELECT 1 FROM public.profile_shops ps WHERE ps.profile_id=p.id AND ps.shop_id=s.id))) $$;
CREATE FUNCTION public.require_shop(p_shop_id uuid) RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path=''
 AS $$ BEGIN IF NOT public.can_access_shop(p_shop_id) THEN RAISE EXCEPTION 'Accès refusé à cette boutique'; END IF; END $$;

