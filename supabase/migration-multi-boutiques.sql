CREATE FUNCTION public.set_staff_shops(p_profile_id uuid,p_shop_ids uuid[]) RETURNS void
 LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$ BEGIN
 IF NOT public.is_admin() THEN RAISE EXCEPTION 'Administratrice uniquement'; END IF;
 PERFORM 1 FROM public.profiles WHERE id=p_profile_id AND role IN ('vendeuse','personnel') FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Personnel introuvable'; END IF;
 IF p_shop_ids IS NULL OR EXISTS(SELECT 1 FROM unnest(p_shop_ids) x WHERE x IS NULL OR NOT EXISTS(
 SELECT 1 FROM public.shops s WHERE s.id=x AND s.active)) THEN RAISE EXCEPTION 'Boutiques invalides'; END IF;
 DELETE FROM public.profile_shops WHERE profile_id=p_profile_id;
 INSERT INTO public.profile_shops SELECT p_profile_id,x FROM (SELECT DISTINCT unnest(p_shop_ids) x) a;
 END $$;

